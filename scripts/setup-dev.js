#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

console.log(
  '🚀 Setting up development environment for Cognito Profile Manager\n'
);

const projectRoot = path.join(__dirname, '..');
const envDevFile = path.join(projectRoot, '.env.development.local');
const envExampleFile = path.join(projectRoot, '.env.development.example');

function generateEncryptionKey() {
  return crypto.randomBytes(32).toString('base64');
}

function createDevEnvFile() {
  const encryptionKey = generateEncryptionKey();

  const envContent = `# Development Environment Configuration
# Generated by setup-dev.js on ${new Date().toISOString()}

# =============================================================================
# APPLICATION CONFIGURATION
# =============================================================================

APP_URL=http://localhost:9002
NODE_ENV=development

# =============================================================================
# SESSION ENCRYPTION (REQUIRED)
# =============================================================================

# Generated encryption key - do not share!
TOTP_SECRET_ENCRYPTION_KEY=${encryptionKey}

# =============================================================================
# AWS COGNITO OAUTH2/OIDC CONFIGURATION (Optional for development)
# =============================================================================

# Uncomment and fill these out when you want to test with real AWS Cognito
# NEXT_PUBLIC_COGNITO_CLIENT_ID=your_cognito_client_id_here
# COGNITO_CLIENT_SECRET=your_cognito_client_secret_here
# NEXT_PUBLIC_COGNITO_WELLKNOWN=https://cognito-idp.us-east-1.amazonaws.com/us-east-1_XXXXXXXXX/.well-known/openid_configuration
# NEXT_PUBLIC_OAUTH2_SCOPE=openid email profile aws.cognito.signin.user.admin
# AWS_REGION=us-east-1
# COGNITO_ADMIN_GROUP_NAME=admins
# COGNITO_GROUPS_CLAIM_KEY=cognito:groups

# =============================================================================
# REDIS/CACHE CONFIGURATION (Optional)
# =============================================================================

# Uncomment if you have Redis running locally
# REDIS_URL=redis://localhost:6379

# =============================================================================
# DEVELOPMENT FEATURES
# =============================================================================

# Enable development features
DEV_MODE=true
`;

  fs.writeFileSync(envDevFile, envContent);
  console.log(
    '✅ Created .env.development.local with generated encryption key'
  );
}

function checkExistingEnvFile() {
  if (fs.existsSync(envDevFile)) {
    console.log('⚠️  .env.development.local already exists');
    console.log('   Delete it and run this script again to regenerate, or');
    console.log('   manually ensure TOTP_SECRET_ENCRYPTION_KEY is set');
    return true;
  }
  return false;
}

function showInstructions() {
  console.log('\n📋 Development Setup Complete!\n');
  console.log('Next steps:');
  console.log('1. Start the development server:');
  console.log('   npm run dev');
  console.log('');
  console.log('2. Open http://localhost:9002 in your browser');
  console.log('');
  console.log('3. Navigate to /login and use the development login options:');
  console.log('   • Click "Admin" for mock admin user');
  console.log('   • Click "User" for mock regular user');
  console.log('   • No AWS Cognito setup required for mock authentication');
  console.log('');
  console.log('🔐 For production OAuth2 authentication:');
  console.log('1. Set up AWS Cognito User Pool and App Client');
  console.log('2. Edit .env.development.local and uncomment Cognito variables');
  console.log('3. Fill in your Cognito configuration values');
  console.log('4. Use "Sign In with SSO" button');
  console.log('');
  console.log('📚 See AUTHENTICATION.md for detailed setup instructions');
  console.log('');
  console.log('🛠️  Useful commands:');
  console.log('   npm run generate:key    # Generate new encryption key');
  console.log('   npm run type:check      # Check TypeScript');
  console.log('   npm run fmt:lint        # Lint and format code');
  console.log('   npm run build:pkg       # Test production build');
}

function main() {
  try {
    if (checkExistingEnvFile()) {
      showInstructions();
      return;
    }

    createDevEnvFile();
    showInstructions();
  } catch (error) {
    console.error('❌ Error setting up development environment:');
    console.error(error.message);
    process.exit(1);
  }
}

// Run if called directly
if (require.main === module) {
  main();
}

module.exports = { generateEncryptionKey, createDevEnvFile };
